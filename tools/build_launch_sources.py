"""Build additive runtime data from reviewed, factual acquisition records."""
from pathlib import Path
import json

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / 'docs/launch-data/sources.json'


def lua(value):
    if value is None: return 'nil'
    if isinstance(value, bool): return 'true' if value else 'false'
    if isinstance(value, (float, int)): return str(value)
    if isinstance(value, str): return json.dumps(value, ensure_ascii=False)
    if isinstance(value, list): return '{' + ','.join(map(lua, value)) + '}'
    return '{' + ','.join('[' + lua(k) + ']=' + lua(v) for k, v in sorted(value.items(), key=lambda p: str(p[0]))) + '}'


def build(data=DATA, output=None, checked='2026-11-05', coverage='LaunchSourceCoverage'):
    reviewed = json.loads(data.read_text(encoding='utf8'))
    items = {int(k): v for k, v in reviewed['items'].items()}
    npcs = {int(k): v for k, v in reviewed['npcs'].items()}
    body = '''-- Generated by tools/build_launch_sources.py from reviewed public facts.
-- Additive source records; no inferred locations, guaranteed rates or live availability.
local _,P=...
'''
    body += 'local items=' + lua(items) + '\nlocal npcs=' + lua(npcs) + '\n'
    body += '''local function add(list,value)
    for _,old in ipairs(list) do if old==value then return end end
    list[#list+1]=value
end
local function clone(value)
    if type(value)~='table' then return value end
    local result={};for k,v in pairs(value) do result[k]=clone(v) end;return result
end
local function identity(s)
    return table.concat({s.kind or '',tostring(s.npc or s.id or ''),s.method or '',s.name or ''},':')
end
local function merge(list,source)
    local key=identity(source)
    for _,old in ipairs(list) do if identity(old)==key then
        -- Keep existing records/coordinates, adding only independently published facts.
        for k,v in pairs(source) do if old[k]==nil then old[k]=clone(v) end end
        return
    end end
    list[#list+1]=clone(source)
end
P.LaunchSourceCoverage={checked='2026-11-05',items={}}
for id,record in pairs(npcs) do
    local npc=P.NPCSources[id]
    if not npc then npc={id=id,name=record.name,points={},entrances={},locations={}};P.NPCSources[id]=npc end
    npc.locations=npc.locations or {}
    for _,zone in ipairs(record.locations or {}) do add(npc.locations,zone) end
    npc.source=npc.source or record.source or 'Wowhead Forever, checked 2026-11-05'
end
-- Reuse only coordinates already attached to the same source ID. No zone centroids.
local sourceMaps={}
for _,entries in pairs(P.GatherAtlas) do for _,entry in ipairs(entries) do
    for _,source in ipairs(entry.sources or {}) do if source.id then
        local key=(source.kind or '')..':'..source.id
        local known=sourceMaps[key] or {mapKeys={},nodeKeys={}};sourceMaps[key]=known
        for _,field in ipairs({'mapKeys','nodeKeys'}) do
            for _,mapKey in ipairs(source[field] or {}) do add(known[field],mapKey) end
        end
    end end
end end
for id,record in pairs(items) do
    local meta=P.ItemMeta[id] or {sources={}};P.ItemMeta[id]=meta
    meta.sources=meta.sources or {};meta.name=record.name;meta.url=record.url
    if record.recipeItem then meta.classID=meta.classID or 9 end
    for _,source in ipairs(record.sources or {}) do merge(meta.sources,source) end
    P.LaunchSourceCoverage.items[id]={status=record.status,url=record.url,captured=record.captured}
    if record.material then
        P.GatherItemNames[id]=record.name
        if P.Items[id] then P.Items[id].name=record.name end
    end
end
for _,entries in pairs(P.Catalog) do for _,recipe in ipairs(entries) do
    local descriptions={};local kinds={}
    for _,ref in ipairs(recipe.acquisitionItems or {}) do
        local record=items[ref.id]
        if record then
            ref.name=record.name
            for _,source in ipairs(record.sources or {}) do
                if source.kind=='Drop' or source.kind=='Vendor' or source.kind=='Quest' then
                    local text=source.kind..': '..source.name
                    if source.zone and source.zone~='' then text=text..' — '..source.zone end
                    if source.favor then text=text..' / '..source.favor.." Merchant's Favor" end
                    if source.reputation then text=text..' / '..source.reputation end
                    add(descriptions,text);kinds[string.lower(source.kind)]=true
                end
            end
        end
    end
    if #descriptions>0 then
        local text=recipe.source or ''
        -- Replace only placeholders, never erase earlier observed alternatives.
        text=text:gsub('Acquisition location not published in this listing%.','')
        text=text:gsub('Acquisition source not yet published; check the linked Forever spell record%.','')
        text=text:gsub('Acquisition location not yet verified%.','')
        for _,line in ipairs(descriptions) do if not text:find(line,1,true) then text=text..'\\n'..line end end
        recipe.source=text:gsub('^%s+',''):gsub('%s+$','')
        recipe.sourceKinds=recipe.sourceKinds or {}
        for kind in pairs(kinds) do recipe.sourceKinds[kind]=true end
        if recipe.sourceKind=='unknown' or not recipe.sourceKind then
            recipe.sourceKind=kinds.vendor and 'vendor' or kinds.drop and 'drop' or 'quest'
        end
        recipe.sourceVerified=true;recipe.acquisitionChecked='2026-11-05'
    end
end end
for _,entries in pairs(P.GatherAtlas) do for _,entry in ipairs(entries) do
    local record=items[entry.item]
    if record and record.material then
        entry.name=record.name;entry.sources=entry.sources or {};entry.referenceURLs=entry.referenceURLs or {}
        entry.mapKeys=entry.mapKeys or {};add(entry.referenceURLs,record.url)
        local search=entry.searchText or ''
        local function searchWord(word)
            if word and word~='' and not search:lower():find(word:lower(),1,true) then search=search..' '..word end
        end
        searchWord(record.name)
        for _,source in ipairs(record.gatherSources or {}) do
            local s=clone(source);local known=sourceMaps[(s.kind or '')..':'..tostring(s.id)]
            s.mapKeys=known and clone(known.mapKeys) or {};s.nodeKeys=known and clone(known.nodeKeys) or {}
            merge(entry.sources,s)
            searchWord(s.name);for _,zone in ipairs(s.zones or {}) do searchWord(zone) end
            for _,key in ipairs(s.mapKeys or {}) do add(entry.mapKeys,key) end
        end
        entry.searchText=search:lower()
        if #(record.gatherSources or {})>0 then
            entry.launchSourceChecked='2026-11-05'
            if entry.sourceCoverage and entry.sourceCoverage.unavailable then entry.sourceCoverage=nil end
        end
    end
end end
'''
    body = body.replace('2026-11-05', checked).replace('LaunchSourceCoverage', coverage)
    output = output or ROOT / 'ProfPaden/Data/LaunchSources.lua'
    output.write_text(body, encoding='utf8', newline='\n')
    return output


if __name__ == '__main__': print(build())
